/// Assembles the AppsFlyer GCD (Get Conversion Data) rescue URL for
/// an organic-mis-classified install. Returns `""` when the base URL
/// or developer key is not yet supplied — callers must treat that as
/// "GCD rescue unavailable" and keep whatever the SDK already reported.
String unwrapGcdCall(String applicationId, String deviceId) {
  final String base = unwrapGcdBase();
  if (base.isEmpty) return '';
  return '$base$applicationId?devkey=${unwrapAttribution()}&device_id=$deviceId';
}
